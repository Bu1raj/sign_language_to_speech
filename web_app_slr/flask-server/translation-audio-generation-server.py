from transformers import AutoTokenizer, AutoModelForSeq2SeqLM, TrainingArguments, Trainer
from datasets import load_dataset, Dataset

# Load and process dataset
import json

with open("/content/train_fixed.json", "r") as file: # you can find the train_fixed.json in the flask-server/training_data folder.
    data = json.load(file)

# Convert to Hugging Face Dataset
dataset = Dataset.from_dict({
    "input": [entry["input"] for entry in data],
    "output": [entry["output"]["text"] for entry in data],
})

# Split dataset into train and test sets
train_test_split = dataset.train_test_split(test_size=0.2)
train_dataset = train_test_split['train']
test_dataset = train_test_split['test']

# Model and tokenizer
model_name = "t5-small"  # You can use any T5-based model
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForSeq2SeqLM.from_pretrained(model_name)

# Tokenization
def preprocess_function(examples):
    inputs = examples["input"]
    print(examples["output"])
    outputs = examples["output"]  # Correct way to access text

    model_inputs = tokenizer(inputs, max_length=128, truncation=True, padding="max_length")
    print("Tokenized inputs:", model_inputs)  # Check tokenized inputs
    labels = tokenizer(outputs, max_length=128, truncation=True, padding="max_length")
    print("Tokenized labels:", labels)  # Check tokenized labels

    model_inputs["labels"] = labels["input_ids"]
    return model_inputs


tokenized_train = train_dataset.map(preprocess_function, batched=True)
tokenized_test = test_dataset.map(preprocess_function, batched=True)

# Training setup
training_args = TrainingArguments(
    output_dir="./results",
    learning_rate=2e-3,
    per_device_train_batch_size=16,
    per_device_eval_batch_size=16,
    num_train_epochs=30,
    weight_decay=0.01,
    save_total_limit=1,
    save_strategy="epoch",
    logging_dir='./logs',
    logging_steps=10,
    push_to_hub=False,
)

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenized_train,
    eval_dataset=tokenized_test,
    tokenizer=tokenizer,
)

# Train the model
trainer.train()

# Save the model
trainer.save_model("finetuned_t5")

